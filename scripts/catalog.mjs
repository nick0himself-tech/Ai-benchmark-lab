// Fetches OpenRouter's public model list (no key, no cost) and writes catalog.json with list prices,
// context size, free/paid status and release date for the models this project actually uses:
// IDs in models.json, OpenRouter IDs recorded in leaderboard.json runs, and any IDs in CATALOG_IDS (comma-separated).
// It does not republish OpenRouter's whole list; each entry is a fact with source and fetch date (see SOURCES.md).
// The advisor reads catalog.json to show API list prices with their source and date.
// Test offline: CATALOG_SRC=path/to/models.json node scripts/catalog.mjs
import fs from 'node:fs';

const SOURCE = 'https://openrouter.ai/api/v1/models';
const src = process.env.CATALOG_SRC;
const raw = src ? JSON.parse(fs.readFileSync(src, 'utf8')) : await (async () => {
  const r = await fetch(SOURCE, { headers: { 'User-Agent': 'ai-benchmark-lab catalog script' } });
  if (!r.ok) throw new Error(`OpenRouter model list: HTTP ${r.status}`);
  return r.json();
})();

const list = Array.isArray(raw?.data) ? raw.data : [];
// A sudden near-empty list means the API changed or failed; keep the old catalogue rather than wiping it.
if (list.length < 20) { console.error(`Only ${list.length} models returned; catalog.json left unchanged.`); process.exit(1); }

// OpenRouter prices are USD per token, as strings. Store USD per million tokens, rounded to avoid float noise.
// A negative price (OpenRouter uses -1 for "varies", e.g. auto routers) is stored as null = unknown.
const perM = v => { const n = Number(v); return Number.isFinite(n) && n >= 0 ? Math.round(n * 1e6 * 10000) / 10000 : null; };
const day = s => (typeof s === 'number' && s > 0 ? new Date(s * 1000).toISOString().slice(0, 10) : null);

// Which IDs to keep.
const want = new Set((process.env.CATALOG_IDS || '').split(',').map(s => s.trim()).filter(Boolean));
const readJson = f => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return null; } };
for (const m of readJson('models.json')?.models || []) if (m?.id) want.add(m.id);
for (const r of readJson('leaderboard.json')?.models || []) {
  const id = r.orId || (/openrouter:\s*([a-z0-9._\/:-]+)/i.exec(`${r.provider || ''} ${r.notes || ''}`) || [])[1];
  if (id) want.add(id);
}

const models = list
  .filter(m => m && typeof m.id === 'string' && want.has(m.id))
  .filter(m => (m.architecture?.output_modalities || ['text']).includes('text'))
  .map(m => {
    const pin = perM(m.pricing?.prompt), pout = perM(m.pricing?.completion);
    return {
      id: m.id,
      name: String(m.name || m.id).slice(0, 120),
      in: pin,   // USD per 1M input tokens
      out: pout, // USD per 1M output tokens
      ctx: Number.isFinite(+m.context_length) ? +m.context_length : null,
      free: m.id.endsWith(':free') || (pin === 0 && pout === 0),
      released: day(m.created),
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const out = {
  _comment: 'Generated by scripts/catalog.mjs from OpenRouter\'s public model list. Prices are API list prices in USD per 1M tokens and change over time; check the source before relying on them.',
  source: SOURCE,
  fetched: new Date().toISOString().slice(0, 10),
  count: models.length,
  missing: [...want].filter(id => !models.some(m => m.id === id)).sort(), // used here but no longer listed by OpenRouter
  models,
};
fs.writeFileSync('catalog.json', JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{') + '\n');
console.log(`catalog.json: ${models.length} of ${want.size} wanted models found in ${list.length} listed (${models.filter(m => m.free).length} free), fetched ${out.fetched}.${out.missing.length ? ' Not listed: ' + out.missing.join(', ') : ''}`);
